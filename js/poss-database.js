(() => {
    'use strict';
    const locale = document.documentElement.lang === 'ru' ? 'ru' : 'en';
    const messages = {
        ru: {
            question: 'Признак', value: 'Значение', example: 'Пример', source: 'Источник', comment: 'Комментарий',
            missing: 'Нет данных', choose: 'Выберите хотя бы один раздел и один язык, затем нажмите «Показать».',
            loading: 'Загрузка данных…', error: 'Не удалось загрузить базу данных. Обновите страницу, чтобы повторить попытку.',
            invalid: 'Некорректный формат базы данных', count: n => `Показано вопросов: ${n}`,
            exportError: 'Экспорт недоступен: библиотека XLSX не загрузилась.', sheet: 'Внешний посессор', section: 'Раздел',
            stats: (q, l) => `Вопросов: ${q}. Языков: ${l}.`
        },
        en: {
            question: 'Feature', value: 'Value', example: 'Example', source: 'Source', comment: 'Comment',
            missing: 'No data', choose: 'Select at least one section and one language, then click Show.',
            loading: 'Loading data…', error: 'Could not load the database. Reload the page to try again.',
            invalid: 'Invalid database format', count: n => `Questions shown: ${n}`,
            exportError: 'Export is unavailable because the XLSX library did not load.', sheet: 'External possessor', section: 'Section',
            stats: (q, l) => `Questions: ${q}. Languages: ${l}.`
        }
    };
    const text = messages[locale];
    const fields = ['example', 'source', 'comment'];
    const get = id => document.getElementById(id);
    let database;
    let sections;
    let displayed = null;
    const name = item => item.label[locale];

    function validate(payload) {
        const fail = () => { throw new Error(text.invalid); };
        if (!payload || payload.schema_version !== 1 ||
            !['sections', 'languages', 'questions'].every(key => Array.isArray(payload[key]) && payload[key].length)) fail();
        for (const key of ['sections', 'languages', 'questions']) {
            const ids = new Set();
            for (const item of payload[key]) {
                if (!item || !/^[a-z][a-z0-9_]*$/.test(item.id) || ids.has(item.id) ||
                    !item.label || !['ru', 'en'].every(lang => typeof item.label[lang] === 'string')) fail();
                ids.add(item.id);
            }
        }
        const known = new Set();
        for (const section of payload.sections) {
            if (section.parent_id !== null && !known.has(section.parent_id)) fail();
            known.add(section.id);
        }
        for (const q of payload.questions) {
            if (!known.has(q.section_id) || !q.answers || payload.languages.some(language =>
                !q.answers[language.id] || ['value', ...fields].some(field => typeof q.answers[language.id][field] !== 'string'))) fail();
        }
    }

    function checkbox(container, prefix, item, checked) {
        const label = document.createElement('label');
        const input = document.createElement('input');
        input.type = 'checkbox';
        input.name = prefix;
        input.value = item.id;
        input.checked = checked;
        label.append(input, document.createTextNode(' ' + name(item)));
        container.append(label);
    }

    function trail(sectionId) {
        const result = [];
        while (sectionId) {
            const section = sections.get(sectionId);
            result.unshift(section);
            sectionId = section.parent_id;
        }
        return result;
    }

    function checked(prefix) {
        return [...document.querySelectorAll(`input[name="${prefix}"]:checked`)].map(input => input.value);
    }

    function appendCell(row, tag, content) {
        const cell = document.createElement(tag);
        cell.textContent = content;
        row.append(cell);
        return cell;
    }

    function answerBlock(field, markup) {
        const wrapper = document.createElement('div');
        wrapper.className = 'poss-answer';
        const label = document.createElement('strong');
        label.textContent = text[field] + ': ';
        wrapper.append(label);
        const content = document.createElement('div');
        content.className = 'poss-content';
        // Only escaped, restricted markup generated by the local builder is published.
        content.innerHTML = markup;
        if (field === 'example') {
            const table = document.createElement('table');
            table.className = 'poss-example';
            table.setAttribute('aria-label', text.example);
            const body = table.createTBody();
            body.insertRow().insertCell().append(content);
            wrapper.append(table);
        } else wrapper.append(content);
        return wrapper;
    }

    function show() {
        const selectedSections = new Set(checked('section'));
        const selectedLanguages = new Set(checked('language'));
        if (!selectedSections.size || !selectedLanguages.size) {
            get('poss-error').textContent = text.choose;
            get('poss-error').hidden = false;
            return;
        }
        get('poss-error').hidden = true;
        const optional = checked('detail');
        const languages = database.languages.filter(language => selectedLanguages.has(language.id));
        const questions = database.questions.filter(q => selectedSections.has(trail(q.section_id)[0].id));
        displayed = {languages, questions, optional};
        render();
    }

    function render() {
        const {languages, questions, optional} = displayed;
        const head = get('poss-head');
        const body = get('poss-body');
        head.replaceChildren();
        body.replaceChildren();
        const headerRow = document.createElement('tr');
        for (const label of [text.question, ...languages.map(name)]) {
            appendCell(headerRow, 'th', label).scope = 'col';
        }
        head.append(headerRow);
        let previous = [];
        for (const q of questions) {
            const path = trail(q.section_id);
            path.forEach((section, index) => {
                if (previous[index]?.id === section.id) return;
                const row = document.createElement('tr');
                row.className = 'poss-section';
                const heading = appendCell(row, 'th', name(section));
                heading.colSpan = languages.length + 1;
                heading.scope = 'rowgroup';
                heading.style.paddingInlineStart = `${12 + index * 18}px`;
                body.append(row);
            });
            previous = path;
            const row = document.createElement('tr');
            appendCell(row, 'th', name(q)).scope = 'row';
            for (const language of languages) {
                const answer = q.answers[language.id];
                const cell = document.createElement('td');
                if (answer.value) cell.append(answerBlock('value', answer.value));
                else {
                    const missing = document.createElement('span');
                    missing.className = 'poss-missing';
                    missing.textContent = text.missing;
                    cell.append(missing);
                }
                for (const field of optional) if (answer[field]) cell.append(answerBlock(field, answer[field]));
                row.append(cell);
            }
            body.append(row);
        }
        get('poss-count').textContent = text.count(questions.length);
        get('poss-results').hidden = false;
        get('poss-instructions').hidden = true;
        get('poss-export').disabled = false;
    }

    function plain(markup) {
        const div = document.createElement('div');
        div.innerHTML = markup;
        return div.textContent;
    }

    function exportDisplayed() {
        if (!displayed) return;
        if (!window.XLSX) {
            get('poss-error').textContent = text.exportError;
            get('poss-error').hidden = false;
            return;
        }
        const {languages, questions, optional} = displayed;
        const rows = [[text.section, text.question, ...languages.map(name)], ...questions.map(q => [
            trail(q.section_id).map(name).join(' → '), name(q), ...languages.map(language => {
                const answer = q.answers[language.id];
                return [`${text.value}: ${answer.value ? plain(answer.value) : text.missing}`,
                    ...optional.filter(field => answer[field]).map(field => `${text[field]}: ${plain(answer[field])}`)].join('\n\n');
            })
        ])];
        const sheet = window.XLSX.utils.aoa_to_sheet(rows);
        sheet['!cols'] = [{wch: 45}, {wch: 55}, ...languages.map(() => ({wch: 65}))];
        const book = window.XLSX.utils.book_new();
        window.XLSX.utils.book_append_sheet(book, sheet, text.sheet);
        window.XLSX.writeFile(book, `external_possessor_${locale}.xlsx`);
    }

    async function init() {
        get('poss-status').textContent = text.loading;
        try {
            const response = await fetch('data/external-possessor.json');
            if (!response.ok) throw new Error(String(response.status));
            database = await response.json();
            validate(database);
            sections = new Map(database.sections.map(s => [s.id, s]));
            database.sections.filter(s => s.parent_id === null).forEach(s => checkbox(get('poss-sections'), 'section', s, true));
            database.languages.forEach(l => checkbox(get('poss-languages'), 'language', l, false));
            get('poss-stats').textContent = text.stats(database.questions.length, database.languages.length);
            get('poss-status').hidden = true;
            get('poss-controls').hidden = false;
            get('poss-instructions').textContent = text.choose;
            get('poss-show').addEventListener('click', show);
            get('poss-export').addEventListener('click', exportDisplayed);
            document.querySelectorAll('[data-poss-select]').forEach(button => {
                button.addEventListener('click', () => {
                    const [group, state] = button.dataset.possSelect.split(':');
                    document.querySelectorAll(`input[name="${group}"]`).forEach(input => { input.checked = state === 'all'; });
                });
            });
        } catch (error) {
            get('poss-status').hidden = true;
            get('poss-error').textContent = text.error;
            get('poss-error').hidden = false;
            console.error(error);
        }
    }
    document.addEventListener('DOMContentLoaded', init);
})();
